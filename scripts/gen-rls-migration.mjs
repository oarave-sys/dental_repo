/**
 * Generates the row-level-security migration from the live schema, so a new
 * tenant-scoped table cannot be added without a policy: the isolation test
 * enumerates the same tables and fails if one is unprotected.
 *
 * Two tiers, because of a genuine bootstrap problem:
 *
 *   STRICT   — every PHI-bearing table. If app.current_org_id is unset the
 *              policy yields zero rows. Forgetting to bind a tenant fails
 *              closed, which is the entire point of the backstop.
 *
 *   BOOTSTRAP — identity tables the app must read *in order to* resolve which
 *              organization a request belongs to (a session token is looked up
 *              before any tenant is known). These allow access when no tenant is
 *              bound, and restrict once one is. They hold PII, not PHI, and are
 *              reached only by a secret token lookup.
 *
 * `users` carries no organization_id at all — a user may belong to several
 * organizations — so it is governed by the application layer.
 */
import pg from 'pg'
import { writeFileSync, mkdirSync } from 'node:fs'
import 'dotenv/config'

const BOOTSTRAP = new Set([
  'organizations',
  'organization_settings',
  'sessions',
  'memberships',
  'roles',
  'membership_roles',
  'invitations',
])

/** Append-only: no UPDATE, no DELETE, ever, by the application role. */
const APPEND_ONLY = ['audit_logs', 'referral_status_history', 'referral_activities']

const APP_ROLE = 'referral_app'

const client = new pg.Client({ connectionString: process.env.DIRECT_DATABASE_URL })
await client.connect()

const { rows } = await client.query(`
  SELECT c.table_name,
         bool_or(c.column_name = 'organizationId') AS has_org
  FROM information_schema.columns c
  JOIN information_schema.tables t
    ON t.table_name = c.table_name AND t.table_schema = c.table_schema
  WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
    AND c.table_name NOT LIKE '\\_prisma%'
  GROUP BY c.table_name
  ORDER BY c.table_name
`)
await client.end()

const lines = []
const p = (s = '') => lines.push(s)

p('-- Row-level security: the fourth layer of tenant isolation.')
p('-- See docs/SECURITY.md §1 Layer 3. Generated by scripts/gen-rls-migration.mjs.')
p('--')
p('-- The application connects as a role with neither SUPERUSER nor BYPASSRLS, so')
p('-- these policies apply to it. FORCE ROW LEVEL SECURITY is deliberately NOT set:')
p('-- the table owner stays exempt so migrations, seeding and retention jobs keep')
p('-- cross-tenant access. Those run offline as a privileged role and are not the')
p('-- surface being defended -- a leaked request handler is.')
p()

const strict = []
const bootstrap = []

for (const r of rows) {
  const t = r.table_name
  if (t === 'users') continue
  if (!r.has_org && t !== 'organizations') continue
  ;(BOOTSTRAP.has(t) ? bootstrap : strict).push(t)
}

const col = (t) => (t === 'organizations' ? 'id' : 'organizationId')

p('-- ---------------------------------------------------------------------------')
p('-- STRICT: unset tenant => zero rows. Fails closed.')
p('-- ---------------------------------------------------------------------------')
for (const t of strict) {
  p(`ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`)
  p(`DROP POLICY IF EXISTS tenant_isolation ON "${t}";`)
  p(`CREATE POLICY tenant_isolation ON "${t}"`)
  p(`  USING ("${col(t)}" = NULLIF(current_setting('app.current_org_id', true), '')::uuid)`)
  p(`  WITH CHECK ("${col(t)}" = NULLIF(current_setting('app.current_org_id', true), '')::uuid);`)
  p()
}

p('-- ---------------------------------------------------------------------------')
p('-- BOOTSTRAP: readable while resolving which tenant a request belongs to,')
p('-- restricted the moment a tenant is bound.')
p('-- ---------------------------------------------------------------------------')
for (const t of bootstrap) {
  p(`ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`)
  p(`DROP POLICY IF EXISTS tenant_isolation ON "${t}";`)
  p(`CREATE POLICY tenant_isolation ON "${t}"`)
  p(`  USING (`)
  p(`    NULLIF(current_setting('app.current_org_id', true), '') IS NULL`)
  p(`    OR "${col(t)}" = NULLIF(current_setting('app.current_org_id', true), '')::uuid`)
  p(`  )`)
  p(`  WITH CHECK (`)
  p(`    NULLIF(current_setting('app.current_org_id', true), '') IS NULL`)
  p(`    OR "${col(t)}" = NULLIF(current_setting('app.current_org_id', true), '')::uuid`)
  p(`  );`)
  p()
}

p('-- ---------------------------------------------------------------------------')
p('-- Append-only tables. Application discipline is not a guarantee:')
p('-- docs/OPEN-QUESTIONS.md A-8.')
p('-- ---------------------------------------------------------------------------')
p(`CREATE OR REPLACE FUNCTION refuse_mutation() RETURNS trigger AS $$`)
p(`BEGIN`)
p(`  -- The owner retains UPDATE/DELETE so retention purges and restores remain`)
p(`  -- possible. The application role never does.`)
p(`  IF current_user = '${APP_ROLE}' THEN`)
p(`    RAISE EXCEPTION '% is append-only; % is not permitted', TG_TABLE_NAME, TG_OP`)
p(`      USING ERRCODE = 'insufficient_privilege';`)
p(`  END IF;`)
p(`  RETURN NULL;`)
p(`END;`)
p(`$$ LANGUAGE plpgsql;`)
p()
for (const t of APPEND_ONLY) {
  p(`REVOKE UPDATE, DELETE ON "${t}" FROM ${APP_ROLE};`)
  p(`DROP TRIGGER IF EXISTS refuse_mutation ON "${t}";`)
  p(`CREATE TRIGGER refuse_mutation BEFORE UPDATE OR DELETE ON "${t}"`)
  p(`  FOR EACH ROW EXECUTE FUNCTION refuse_mutation();`)
  p()
}

p('-- Ensure the app role can reach tables created by this and future migrations.')
p(`GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${APP_ROLE};`)
p(`GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${APP_ROLE};`)
for (const t of APPEND_ONLY) p(`REVOKE UPDATE, DELETE ON "${t}" FROM ${APP_ROLE};`)

const dir = 'prisma/migrations/20260828234500_row_level_security'
mkdirSync(dir, { recursive: true })
writeFileSync(`${dir}/migration.sql`, lines.join('\n') + '\n')
console.log(`strict: ${strict.length}  bootstrap: ${bootstrap.length}  -> ${dir}/migration.sql`)
console.log('strict tables:', strict.join(', '))
