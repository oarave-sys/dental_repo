/**
 * Generates the row-level-security migration from the Prisma schema.
 *
 * Written rather than hand-maintained because a forgotten policy is silent:
 * the application keeps working, and the only sign is that a table has no
 * backstop. Deriving the tiers from the schema means adding a model with an
 * organizationId automatically gets one.
 *
 *   TENANT     organizationId must equal app.current_org_id
 *   BOOTSTRAP  readable before a tenant is known (session lookup, sign-up)
 *   REFERENCE  global procedure-code data: readable by all, written by the owner
 *
 * Usage: node scripts/gen-rls-migration.mjs > prisma/migrations/<name>/migration.sql
 */
import { readFileSync } from 'node:fs'

const schema = readFileSync('prisma/schema.prisma', 'utf8')

/** Model name -> mapped table name, plus whether it carries organizationId. */
const models = []
const modelBlocks = schema.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)
for (const [, name, body] of modelBlocks) {
  const mapped = body.match(/@@map\("([^"]+)"\)/)?.[1]
  if (!mapped) throw new Error(`Model ${name} has no @@map`)
  models.push({
    name,
    table: mapped,
    tenantScoped: /^\s*organizationId\s+String/m.test(body),
  })
}

/**
 * Identity tables, checked BEFORE tenant scoping even though several of them
 * carry organizationId.
 *
 * They have to be: resolving a session token is what discovers which
 * organization a request belongs to, so the lookup necessarily happens with
 * app.current_org_id unset. A strict tenant policy here would return zero rows
 * and nobody could sign in.
 *
 * These are still tenant-scoped at the application layer — the Prisma
 * extension injects organizationId for every tenant-bound client, and only the
 * deliberately-ugly unsafeCrossTenantClient() reaches them unscoped. They hold
 * account records, not clinical content.
 */
const BOOTSTRAP = new Set([
  'organizations',
  'users',
  'sessions',
  'organization_members',
  'invitations',
  'password_reset_tokens',
])

/**
 * Append-only tables. Tenant-scoped for reading, but the policy grants only
 * INSERT and SELECT — there is deliberately no UPDATE or DELETE policy, so
 * PostgreSQL refuses both even for the application role. An audit log the
 * application can rewrite is not an audit log.
 */
const APPEND_ONLY = new Set(['audit_events'])

const REFERENCE = new Set([
  'code_datasets',
  'procedure_codes',
  'procedure_code_attributes',
  'procedure_code_relationships',
  'documentation_rules',
])

const out = []
out.push('-- Row-level security.')
out.push('--')
out.push('-- Generated by scripts/gen-rls-migration.mjs. Do not edit by hand.')
out.push('--')
out.push('-- This is the backstop beneath the application-level tenant filter, and it')
out.push('-- only works if the application connects as a role that is NOT a superuser')
out.push('-- and does NOT have BYPASSRLS. See docs/SECURITY.md.')
out.push('')

for (const model of models) {
  const t = model.table
  out.push(`ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`)

  if (REFERENCE.has(t)) {
    // NOT forced, deliberately. The table owner — the role the importer runs
    // as — is exempt from RLS unless FORCE is set, which is exactly the
    // intended split: the importer writes, the application only reads. The
    // application role does not own these tables, so the SELECT-only policy
    // below is what it gets.
    out.push(`-- REFERENCE: global procedure-code data, readable by every tenant.`)
    out.push(`-- Writable only by the table owner (the importer). RLS is not FORCEd`)
    out.push(`-- here so that the owner can load a dataset; the application role is`)
    out.push(`-- not the owner and is confined to SELECT by this policy.`)
    out.push(`CREATE POLICY "${t}_read" ON "${t}" FOR SELECT USING (true);`)
  } else if (BOOTSTRAP.has(t)) {
    out.push(`ALTER TABLE "${t}" FORCE ROW LEVEL SECURITY;`)
    // Deliberately ahead of the tenant check: see the note on BOOTSTRAP above.
    out.push(`-- BOOTSTRAP: identity, reached by secret token before a tenant is known.`)
    out.push(`CREATE POLICY "${t}_bootstrap" ON "${t}" USING (true) WITH CHECK (true);`)
  } else if (APPEND_ONLY.has(t)) {
    out.push(`ALTER TABLE "${t}" FORCE ROW LEVEL SECURITY;`)
    out.push(`-- APPEND-ONLY: insert and read within the tenant; no UPDATE or`)
    out.push(`-- DELETE policy exists, so PostgreSQL refuses both outright.`)
    out.push(
      `CREATE POLICY "${t}_insert" ON "${t}" FOR INSERT WITH CHECK (` +
        `"organizationId" = NULLIF(current_setting('app.current_org_id', true), '')::uuid);`,
    )
    out.push(
      `CREATE POLICY "${t}_select" ON "${t}" FOR SELECT USING (` +
        `"organizationId" = NULLIF(current_setting('app.current_org_id', true), '')::uuid);`,
    )
  } else if (model.tenantScoped) {
    out.push(`ALTER TABLE "${t}" FORCE ROW LEVEL SECURITY;`)
    out.push(`-- TENANT: reachable only within the bound organization.`)
    // NULLIF is load-bearing, not defensive noise. set_config(..., true) is
    // transaction-local, and when that transaction ends Postgres resets the
    // GUC to an EMPTY STRING rather than leaving it unset. On a pooled
    // connection that has previously served a tenant request, a later
    // unscoped query would then evaluate ''::uuid and raise
    // "invalid input syntax for type uuid" instead of simply matching no
    // rows. NULLIF turns that back into NULL, so the comparison yields NULL
    // and the row stays invisible — which is the intended behaviour.
    out.push(
      `CREATE POLICY "${t}_tenant" ON "${t}" USING (` +
        `"organizationId" = NULLIF(current_setting('app.current_org_id', true), '')::uuid` +
        `) WITH CHECK (` +
        `"organizationId" = NULLIF(current_setting('app.current_org_id', true), '')::uuid);`,
    )
  } else {
    throw new Error(
      `Table "${t}" is neither tenant-scoped nor in a known tier. ` +
        `Add it to BOOTSTRAP or REFERENCE in scripts/gen-rls-migration.mjs, ` +
        `or give its model an organizationId.`,
    )
  }
  out.push('')
}

process.stdout.write(out.join('\n'))
